  var cache = {};
  function grid(r) { return r.map(function (s) { return s.split(""); }); }
  // x0〜x1 の列の足（下から5行）を1点上げる（歩く）
  function lift(g, x0, x1) {
    var h = g.length, y, x;
    for (y = h - 5; y < h; y++) for (x = x0; x <= x1; x++) if (g[y][x] !== ".") g[y - 1][x] = g[y][x];
    for (x = x0; x <= x1; x++) g[h - 1][x] = ".";
  }
  // 地図を絵にする。flip：左右反転。white：当たったときの白い絵（ふちどりはそのまま）
  function toCanvas(g, flip, white, pal) {
    var h = g.length, w = g[0].length;
    pal = pal || PAL;
    var cv = document.createElement("canvas"); cv.width = w; cv.height = h;
    var ctx = cv.getContext("2d");
    for (var y = 0; y < h; y++) for (var x = 0; x < w; x++) {
      var ch = g[y][x], col = pal[ch];
      if (!col) continue;
      ctx.fillStyle = white && ch !== "A" ? WHITE : col;
      ctx.fillRect(flip ? w - 1 - x : x, y, 1, 1);
    }
    return cv;
  }
  function dirOf(face) {
    if (Math.abs(face.x) > Math.abs(face.y) + 0.01) return { dir: "side", flip: face.x > 0 };   // 地図は左向き
    return { dir: face.y < 0 ? "up" : "down", flip: false };
  }
  // ふつうの敵の絵。frame：stand・walkA・walkB（蜂は stand・flap）
  function small(type, dir, frame, white) {
    var k = type + "|" + dir + "|" + frame + "|" + (white ? 1 : 0);
    if (cache[k]) return cache[k];
    var ph = !SMALL[type] && PLACEHOLDER[type];
    var m = SMALL[type] || (ph && SMALL[ph.base]) || SMALL.goblin_sword;
    if (frame === "flap") { cache[k] = toCanvas(grid(m[dir + "B"] || m[dir] || m.down), false, white); return cache[k]; }
    var g = grid(m[dir] || m.down);
    var sw = STATUE[type] || (ph && ph.swap);
    if (sw) g = g.map(function (row) { return row.map(function (ch) { return sw[ch] || ch; }); });
    var kd = GameData.ENEMIES[type] ? GameData.ENEMIES[type].kind : "";
    // 足を動かさない敵：つる草・蜂やコウモリ（飛ぶ）・はねる敵・浮く敵・魔導士・岩の虫（はう）・スライム
    if (frame !== "stand" && type !== "vine" && kd !== "bee" && kd !== "frog" && kd !== "wisp" && type !== "dark_wisp" && type !== "shadow_mage" && type !== "rock_worm") {
      var a = frame === "walkA";
      if (dir === "side") { if (a) lift(g, 0, 7); else lift(g, 8, 15); }
      else { if (a) lift(g, 2, 7); else lift(g, 8, 13); }
    }
    cache[k] = toCanvas(g, false, white);
    return cache[k];
  }
  // 足もと（x, y）を基準に描く
  function drawSmall(ctx, e, x, y) {
    var d = dirOf(e.face), ph = Math.sin(e.walk || 0), moving = e.def.speed > 0 && (e.state === "chase" || e.state === "charge");
    var frame = !moving ? "stand" : ph > 0.3 ? "walkA" : ph < -0.3 ? "walkB" : "stand";
    if (e.type === "vine") d = { dir: "down", flip: false };
    if (e.def.kind === "bee") frame = Math.floor(Date.now() / (e.type === "bat" ? 110 : 70)) % 2 ? "flap" : "stand";   // 蜂と大コウモリは、いつもはばたく
    var img = small(e.type, d.dir, frame, e.flash > 0);
    ctx.save();
    if (d.flip) { ctx.translate(Math.round(x), 0); ctx.scale(-1, 1); ctx.drawImage(img, -8, Math.round(y) - img.height); }
    else ctx.drawImage(img, Math.round(x) - 8, Math.round(y) - img.height);
    ctx.restore();
  }
  // ボス。kind：wolf_boss・tree_boss。frame は WOLF・TREE の名前
  function boss(kind, frame, white) {
    var k = kind + "|" + frame + "|" + (white ? 1 : 0);
    if (cache[k]) return cache[k];
    var set = kind === "wolf_boss" ? WOLF : kind === "frog_boss" ? FROGB : kind === "witch_boss" ? WITCH : kind === "golem_boss" ? GOLEM : kind === "elf_boss" ? ELF : TREE;
    cache[k] = toCanvas(grid(set[frame] || set.stand), false, white, BOSS_PAL[kind]);
    return cache[k];
  }
  // 足もと（x, y）を基準に描く。face.x が正なら右向き（大オオカミの地図は左向き）
  function drawBoss(ctx, e, x, y, frame) {
    var img = boss(e.def.kind, frame, e.flash > 0);
    var flip = (e.def.kind === "wolf_boss" || e.def.kind === "elf_boss") && e.face.x > 0;   // ダークエルフの絵は、弓を左へ向けている
    ctx.save();
    if (flip) { ctx.translate(Math.round(x), 0); ctx.scale(-1, 1); ctx.drawImage(img, -Math.round(img.width / 2), Math.round(y) - img.height); }
    else ctx.drawImage(img, Math.round(x) - Math.round(img.width / 2), Math.round(y) - img.height);
    ctx.restore();
  }

  // ボスの絵の足もと：ボスのまんなか（e.y）から何点下か
  function bossFoot(kind) { return kind === "wolf_boss" ? 11 : kind === "frog_boss" ? 14 : kind === "witch_boss" ? 14 : kind === "golem_boss" ? 16 : kind === "elf_boss" ? 14 : 18; }
  return { drawSmall: drawSmall, drawBoss: drawBoss, small: small, boss: boss, bossFoot: bossFoot };
